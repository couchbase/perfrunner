import glob
import os
import re
import tempfile
from unittest import TestCase

import yaml

from perfrunner.settings import TestConfig
from perfrunner.workloads.analytics.custom.driver import (
    expand_query_configs,
    split_query_conf,
    validate_ratios,
)

# Importing perfrunner.tests.analytics configures celery, which needs a worker type
os.environ.setdefault("WORKER_TYPE", "local")

from perfrunner.tests import analytics  # noqa: E402

FUNCTION_CONF = "perfrunner/workloads/analytics/udf/python_udf_functions.yaml"
QUERY_CONFS = glob.glob("perfrunner/workloads/analytics/custom/python_udf_*.yaml")
TEST_CONFIGS = glob.glob("tests/cloud/analytics/*_python_udf_*.test")


def load_yaml_conf(conf, loader):
    with tempfile.NamedTemporaryFile("w", suffix=".yaml") as f:
        yaml.safe_dump(conf, f)
        f.flush()
        return loader(f.name)


class PythonUDFTest(TestCase):
    def test_udf_ddl(self):
        sqlpp = analytics.UDFDef("net_pay_sqlpp", ("bal", "ytd", "disc"), body="{ }")
        python = analytics.UDFDef(
            "net_pay_py", ("bal", "ytd", "disc"), external=("udf_mod", "Metrics.net_pay")
        )
        self.assertEqual(
            sqlpp.create_statement(None),
            "CREATE FUNCTION `net_pay_sqlpp`(bal, ytd, disc) { { } }",
        )
        self.assertEqual(
            python.create_statement("pylib"),
            'CREATE ANALYTICS FUNCTION `net_pay_py`(bal, ytd, disc) AS "udf_mod", '
            '"Metrics.net_pay" AT `pylib`',
        )

    def test_udf_config(self):
        self.assertEqual(analytics.load_udf_config(None), (None, []))

        library, udfs = analytics.load_udf_config(FUNCTION_CONF)
        self.assertTrue(os.path.isdir(library.module_dir))
        self.assertTrue(any(u.is_python for u in udfs))

        for bad in (
            {"functions": [{"name": "f", "args": [], "body": "1", "external": ["m", "e"]}]},
            {"functions": [{"name": "f", "args": []}]},
            {"functions": [{"name": "f", "args": [], "external": ["m", "e"]}]},
        ):
            with self.assertRaises(ValueError):
                load_yaml_conf(bad, analytics.load_udf_config)

    def test_derived_dataset_ddl(self):
        derived = analytics.StandaloneDatasetDef(
            "customer_1m", ["id"], ["uuid"], query="SELECT VALUE d FROM customer_ext d LIMIT 10"
        )
        self.assertEqual(
            derived.create_statement(),
            "CREATE COLLECTION `customer_1m` PRIMARY KEY (`id`: `uuid`) AUTOGENERATED AS "
            "SELECT VALUE d FROM customer_ext d LIMIT 10",
        )
        self.assertFalse(derived.needs_ingest())

        imported = analytics.StandaloneDatasetDef("orders", ["id"], ["string"])
        self.assertTrue(imported.needs_ingest())
        self.assertEqual(
            analytics.DatasetCollection([imported, derived], {}).derived(), [derived]
        )

    def test_derived_dataset_configs(self):
        parse = analytics.DatasetConfigParser._derived_datasets
        for conf_file in glob.glob("tests/analytics/config/python_udf_*_datasets.yaml"):
            datasets = parse(conf_file)
            names = [d.name for d in datasets]
            for i, dataset in enumerate(datasets):
                self.assertIsNotNone(dataset.expected_items, dataset.name)
                # Created in order, so a dataset may only read those defined above it
                for later in names[i:]:
                    self.assertNotIn(f" {later} ", f" {dataset.query} ", conf_file)

        with self.assertRaises(ValueError):
            load_yaml_conf([{"name": "x", "query": "SELECT 1", "limit": 1}], parse)

    def test_query_configs(self):
        for conf_file in QUERY_CONFS:
            with open(conf_file) as f:
                configs, ratios = split_query_conf(yaml.safe_load(f))
            expand_query_configs(configs)
            validate_ratios(configs, ratios)
            if "placement" in conf_file:
                for conf in configs:
                    if conf.get("name"):
                        self.assertEqual(conf["plan_order"], ["score_py(", "_JOIN"])

    def test_test_configs(self):
        for test_file in TEST_CONFIGS:
            test_config = TestConfig()
            test_config.parse(test_file)
            settings = test_config.analytics_settings
            self.assertTrue(test_config.showfast.title)
            self.assertEqual(settings.udf_conf_file, FUNCTION_CONF)
            for conf_file in (
                settings.dataset_conf_file,
                settings.custom_query_conf_file,
                settings.derived_dataset_conf_file,
            ):
                if conf_file:
                    self.assertTrue(os.path.exists(conf_file), f"{test_file}: {conf_file}")

    def test_python_udfs_never_appear_in_where_clauses(self):
        # An external UDF in a WHERE predicate fails to compile (24001)
        with open(FUNCTION_CONF) as f:
            py_names = [fn["name"] for fn in yaml.safe_load(f)["functions"] if fn.get("external")]

        for conf_file in QUERY_CONFS:
            with open(conf_file) as f:
                configs, _ = split_query_conf(yaml.safe_load(f))
            for conf in configs:
                flat = " ".join(conf["statement"].split())
                for predicate in re.split(r"\bWHERE\b", flat)[1:]:
                    for name in py_names:
                        self.assertNotIn(f"{name}(", predicate, f"{conf_file}: {flat}")
